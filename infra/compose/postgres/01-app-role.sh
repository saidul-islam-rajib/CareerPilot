#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE ${CAREERPILOT_APP_DB_USER} LOGIN PASSWORD '${CAREERPILOT_APP_DB_PASSWORD}';
GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${CAREERPILOT_APP_DB_USER};
GRANT USAGE ON SCHEMA public TO ${CAREERPILOT_APP_DB_USER};
ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public GRANT SELECT, INSERT, UPDATE ON TABLES TO ${CAREERPILOT_APP_DB_USER};
ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ${CAREERPILOT_APP_DB_USER};
SQL
